def regime_for(f, n):
    rid = (f.get('regime_of') or {}).get(n, f['regimes'][0]['id'])
    return [r for r in f['regimes'] if r['id'] == rid][0]


def check():
    seen = {}
    for f in FOLDERS:
        for n in f['cards']:
            assert n not in seen, 'карта %d в двух папках: %s и %s' % (n, seen[n], f['code'])
            seen[n] = f['code']
        for n in (f.get('regime_of') or {}):
            assert n in f['cards'], 'режим для карты %d не из папки %s' % (n, f['code'])
    missing = [n for n in range(1, 235) if n not in seen]
    assert not missing, 'карты без папки: %s' % missing
    return seen


