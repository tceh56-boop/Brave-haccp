def shade(cell, hex_):
    tcPr = cell._tc.get_or_add_tcPr(); s = OxmlElement('w:shd')
    s.set(qn('w:val'), 'clear'); s.set(qn('w:color'), 'auto'); s.set(qn('w:fill'), hex_); tcPr.append(s)


def H1(t):
    doc.add_page_break(); doc.add_heading(t, 1)


def H2(t): doc.add_heading(t, 2)
def H3(t): doc.add_heading(t, 3)


def P(t, bold_prefix=None, italic=False, color=None):
    p = doc.add_paragraph()
    if bold_prefix:
        r = p.add_run(bold_prefix); r.bold = True
    r = p.add_run(t); r.italic = italic
    if color: r.font.color.rgb = color
    return p


def steps(items):
    for i, t in enumerate(items, 1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.8); p.paragraph_format.first_line_indent = Cm(-0.6)
        r = p.add_run('%d.  ' % i); r.bold = True; r.font.color.rgb = NAVY
        p.add_run(t)


def bullets(items):
    for t in items:
        p = doc.add_paragraph(style='List Bullet')
        if isinstance(t, tuple):
            r = p.add_run(t[0]); r.bold = True; p.add_run(t[1])
        else:
            p.add_run(t)


def note(t, kind='info'):
    tbl = doc.add_table(rows=1, cols=1); tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = tbl.rows[0].cells[0]; shade(c, {'info': 'E8F0FE', 'warn': 'FFF4E5', 'bad': 'FDECEC'}[kind])
    c.paragraphs[0].add_run({'info': 'Важно. ', 'warn': 'Внимание. ', 'bad': 'Нельзя. '}[kind]).bold = True
    c.paragraphs[0].add_run(t)
    doc.add_paragraph()


def img(name, width=16, caption=None):
    path = os.path.join(SHOTS, name + '.png')
    if not os.path.exists(path):
        print('MISSING', name); return
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = bool(caption)
    p.add_run().add_picture(path, width=Cm(width))
    if caption:
        c = doc.add_paragraph(); c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.add_run(caption); r.italic = True; r.font.size = Pt(9); r.font.color.rgb = GREY


def fields(rows, head=('Поле', 'Обяз.', 'Что вводить')):
    tbl = doc.add_table(rows=1, cols=len(head)); tbl.style = 'Table Grid'; tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    widths = [Cm(4.2), Cm(1.8), Cm(11.0)] if len(head) == 3 else [Cm(5), Cm(12)]
    for i, h in enumerate(head):
        c = tbl.rows[0].cells[i]; c.text = ''; r = c.paragraphs[0].add_run(h); r.bold = True; r.font.color.rgb = RGBColor(255, 255, 255); shade(c, '0B2A5B')
    for row in rows:
        cells = tbl.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            run = cells[i].paragraphs[0].add_run(v)
            run.font.size = Pt(9.5)
            if i == 0: run.bold = True
            if len(head) == 3 and i == 1: cells[i].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
    tbl.autofit = False
    for i, w in enumerate(widths): tbl.columns[i].width = w
    for row in tbl.rows:
        for i, w in enumerate(widths): row.cells[i].width = w
    doc.add_paragraph()


