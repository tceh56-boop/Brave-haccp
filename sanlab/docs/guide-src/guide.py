def fmt(t):
    """[[Кнопка]] — кнопка, {{Кнопка}} — главная кнопка, ((3)) — номер шага, **жирный**, Раздел → Экран."""
    t = html.escape(t, quote=False)
    t = re.sub(r'\{\{(.+?)\}\}', r'<span class="chip pri">\1</span>', t)
    t = re.sub(r'\[\[(.+?)\]\]', r'<span class="chip">\1</span>', t)
    t = re.sub(r'\(\((\d+)\)\)', r'<span class="n">\1</span>', t)
    t = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', t)
    t = re.sub(r'__(.+?)__', r'<i>\1</i>', t)
    t = t.replace(' → ', ' <span class="ar">→</span> ')
    return t


SECTIONS = []
def H1(num, title, who=None, where=None, intro=None):
    sid = 's%s' % num
    SECTIONS.append((num, title))
    add('<section class="sec" id="%s"><h1>%s%s</h1>' % (sid, (str(num) + '. ') if num else '', html.escape(title)))
    if who or where:
        add('<div class="who">%s%s</div>' % (
            ('<div><b>Кто:</b> %s</div>' % fmt(who)) if who else '',
            ('<div><b>Где:</b> %s</div>' % fmt(where)) if where else ''))
    if intro: P(intro)

def END(): add('</section>')
def H2(t, brk=False): add('<h2%s>%s</h2>' % (' class="brk"' if brk else '', fmt(t)))
def H3(t): add('<h3>%s</h3>' % fmt(t))
def P(t, cls=''): add('<p class="%s">%s</p>' % (cls, fmt(t)))
def NOTE(t): add('<p class="note">%s</p>' % fmt(t))


def STEPS(items, numbered=True):
    out = ['<ol class="steps">']
    for i, it in enumerate(items, 1):
        if isinstance(it, tuple):
            n, t = it
        else:
            n, t = i, it
        out.append('<li><span class="n">%s</span><div>%s</div></li>' % (n, fmt(t)) if numbered else '<li><span class="dot"></span><div>%s</div></li>' % fmt(t))
    out.append('</ol>')
    return ''.join(out)


def BOX(kind, title, text):
    """kind: warn | bad | ok | info"""
    if isinstance(text, list):
        inner = '<ul>' + ''.join('<li>%s</li>' % fmt(x) for x in text) + '</ul>'
    else:
        inner = '<div>%s</div>' % fmt(text)
    return '<div class="box %s"><div class="bt">%s</div>%s</div>' % (kind, fmt(title), inner)


def box(kind, title, text): add(BOX(kind, title, text))


def FIG(img, steps=None, title=None, layout='full', boxes=(), w=None, plain=False):
    """layout: full — снимок на всю ширину, шаги ниже; side — снимок слева, шаги справа; modal — форма по центру."""
    src = '%s/%s.jpg' % (IMG, img)
    st = STEPS(steps, numbered=not plain) if steps else ''
    bx = ''.join(BOX(*b) for b in boxes)
    h = ('<h3 class="ft">%s</h3>' % fmt(title)) if title else ''
    if layout == 'side':
        add('<div class="blk">%s<div class="side"><div class="shot m" style="%s"><img src="%s"></div><div class="txt">%s%s</div></div></div>' % (h, ('flex:0 0 %s' % w) if w else '', src, st, bx))
    elif layout == 'modal':
        add('<div class="blk">%s<div class="fig"><div class="shot md" style="%s"><img src="%s"></div></div>%s%s</div>' % (h, ('width:%s' % w) if w else '', src, st, bx))
    else:
        add('<div class="blk">%s<div class="fig"><div class="shot d" style="%s"><img src="%s"></div></div>%s%s</div>' % (h, ('width:%s' % w) if w else '', src, st, bx))


def TABLE(head, rows, widths=None, cls=''):
    out = ['<table class="t %s">' % cls]
    if widths: out.append('<colgroup>' + ''.join('<col style="width:%s">' % w for w in widths) + '</colgroup>')
    out.append('<thead><tr>' + ''.join('<th>%s</th>' % fmt(h) for h in head) + '</tr></thead><tbody>')
    for r in rows:
        out.append('<tr>' + ''.join('<td>%s</td>' % fmt(c) for c in r) + '</tr>')
    out.append('</tbody></table>')
    add(''.join(out))


