/**
 * Единый знак обращения продукции ЕАС — по масштабной сетке 9×9 (Положение о едином знаке обращения, решение Комиссии
 * Таможенного союза от 15.07.2011 N 711, рис. 3): буквы «Е», «А», «С» из прямоугольников, пропорции квадрата.
 * Одноцветный, контрастный фону (п. 5.2); базовый размер — не менее 5 мм (п. 3.3).
 * Закрашенные клетки [строка, столбец], нумерация с 1, как на рис. 3.
 */
const CELLS: [number, number][] = [
  // «Е»: столбец 1 целиком; верх, середина, низ — столбцы 1–2
  ...[1, 2, 3, 4, 5, 6, 7, 8, 9].map((r) => [r, 1] as [number, number]), [1, 2], [5, 2], [9, 2],
  // «А»: столбцы 4 и 6 целиком; перекладины в строках 1 и 5 — столбец 5
  ...[1, 2, 3, 4, 5, 6, 7, 8, 9].flatMap((r) => [[r, 4], [r, 6]] as [number, number][]), [1, 5], [5, 5],
  // «С»: столбец 8 целиком; верх и низ — столбец 9
  ...[1, 2, 3, 4, 5, 6, 7, 8, 9].map((r) => [r, 8] as [number, number]), [1, 9], [9, 9],
];

export function EacMark({ sizeMm = 8, color = '#000', title = 'Единый знак обращения продукции ЕАС' }: { sizeMm?: number; color?: string; title?: string }) {
  const s = Math.max(5, sizeMm);
  return (
    <svg className="eac-mark" viewBox="0 0 9 9" width={`${s}mm`} height={`${s}mm`} role="img" aria-label={title} shapeRendering="crispEdges">
      <title>{title}</title>
      {CELLS.map(([r, c]) => <rect key={`${r}-${c}`} x={c - 1} y={r - 1} width={1.01} height={1.01} fill={color} />)}
    </svg>
  );
}
